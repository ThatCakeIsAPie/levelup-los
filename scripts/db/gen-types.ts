/**
 * Regenerates src/data/remote/database.types.ts from the running local
 * database (`npm run db:types`), then formats it with Prettier.
 */
import { execSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const target = resolve(root, "src/data/remote/database.types.ts");

const types = execSync("npx supabase gen types typescript --local --schema public", {
  cwd: root,
  encoding: "utf8",
  stdio: ["ignore", "pipe", "inherit"],
  maxBuffer: 32 * 1024 * 1024,
});
if (!types.includes("export type Database")) {
  throw new Error("supabase gen types returned no types (is the local database running?)");
}

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `// GENERATED by \`npm run db:types\` (supabase gen types) from the local database.\n// Do not edit by hand.\n${types}`,
  "utf8",
);
execSync(`npx prettier --write "${target}"`, { cwd: root, stdio: "inherit" });
console.log(`Wrote ${target}`);
